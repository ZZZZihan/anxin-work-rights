def ask(missing=(), conflicts=()):
    fields = list(missing) + list(conflicts)
    return {"missing": list(missing), "conflicts": list(conflicts), "next_action": {
        "type": "ask_user", "questions": [{"field": f, "text": QUESTIONS[f]} for f in fields],
        "tool": None, "arguments": None}}

def call(start, end, due, paid):
    return {"missing": [], "conflicts": [], "next_action": {"type": "call_tool", "questions": [],
        "tool": "calculate_wage_gap", "arguments": {
            "period_start": start, "period_end": end, "due": due, "paid": paid}}}

def fail():
    return {"missing": [], "conflicts": [], "next_action": {"type": "report_tool_failure", "questions": [],
        "tool": None, "arguments": None}}

def U(text): return {"role": "user", "content": text}
def A(text): return {"role": "assistant", "content": text}

DATA = {"train": [], "dev": [], "test": []}
SERIAL = 0
GROUPS = []

def group(split, description, *rows):
    global SERIAL
    group_id = "g" + str(len(GROUPS) + 1).zfill(3)
    GROUPS.append({"group_id": group_id, "split": split, "description": description, "size": len(rows)})
    for row in rows:
        category, messages, expected, rationale, *tool_state = row
        SERIAL += 1
        case_id = "c_" + uuid5(NAMESPACE_URL, f"decision-baseline-v1-authoring-{SERIAL}").hex[:12]
        record = {"id": case_id, "messages": messages,
                  "tool_state": tool_state[0] if tool_state else None}
        label = {"id": case_id, "split": split, "group_id": group_id, "category": category,
                 "synthetic": True, "provenance": "agent_authored_synthetic",
                 "expected": expected, "rationale": rationale}
        DATA[split].append((record, label))

