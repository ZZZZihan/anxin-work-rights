import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {readFile} from 'node:fs/promises';
import {pathToFileURL} from 'node:url';
import {resolve} from 'node:path';
const root=process.argv[2]; if(!root)throw new Error('Expected a read-only source root');
const load=p=>import(pathToFileURL(resolve(root,p)));
const {normalizeCandidateValueV4:normalize}=await load('lib/material-money-v4.ts');
const {ingestRuntimeCandidates:fresh}=await load('lib/material-fact-runtime-ingest.ts');
const {ingestCandidates:legacy,emptyFactState}=await load('lib/material-facts-v3.ts');
const {reviewFactsAgainstSources:review}=await load('lib/material-fact-source-review.ts');
for(const path of ['lib/material-money-v4.ts','lib/material-fact-range-review.ts','lib/material-fact-source-review.ts'])console.log(JSON.stringify({path,sha256:createHash('sha256').update(await readFile(resolve(root,path))).digest('hex')}));
const cases=[];
for(const [prefix,value]of [['负','四万元'],['負','四万元'],['数','十万元'],['數','十万元']])for(const layout of ['line','blocks'])cases.push({prefix,value,blocks:layout==='line'?['😀王甲工资'+prefix+'\n'+value+'。']:['😀王甲工资'+prefix,value+'。'],blockId:layout==='line'?'b1':'b2',expected:null});
cases.push({blocks:['李乙工资为负；😀王甲工资四万元。'],blockId:'b1',value:'四万元',expected:'40000.00'});
cases.push({blocks:['李乙工资为未知数。😀王甲工资十万元。'],blockId:'b1',value:'十万元',expected:'100000.00'});
let failed=0;
for(const spec of cases){
 const source={id:'layout-sign-count-probe',name:'synthetic.txt',sha256:'e'.repeat(64),analysisRevision:15,ready:true,blocks:spec.blocks.map((text,i)=>({id:'b'+(i+1),text,page:1,bbox:null,confidence:null}))};
 const candidate={kind:'money',value:spec.value,quote:spec.value,blockId:spec.blockId,subject:'王甲',scope:'individual',meaning:'due_total',completeness:'complete',period:null,rateUnit:null,assertion:'narrated'};
 const raw=JSON.stringify({schemaVersion:3,candidates:[candidate]});
 const ingest=fn=>fn(emptyFactState(15),source,{raw},'layout-sign-count-probe','synthetic','2026-10-18T08:00:00.000Z',null);
 const state=ingest(fresh),old=ingest(legacy);assert.equal(state.materials[0].raw,raw);assert.equal(state.materials[0].candidates.length,1);
 const historical=old.materials[0].candidates[0],baseAmount=spec.value==='四万元'?'40000.00':'100000.00';
 historical.amount=baseAmount;historical.normalization={rawValue:spec.value,status:'exact',amount:baseAmount,matchedText:spec.value,span:{start:0,end:Array.from(spec.value).length},reason:'Synthetic unsafe exact history'};
 const before=JSON.stringify(old),r=review(old,[source]);assert.equal(JSON.stringify(old),before);assert.equal(r.materials[0].raw,raw);
 const amounts={fresh:state.materials[0].candidates[0].amount,history:r.materials[0].candidates[0].amount};
 if(spec.blocks.length===1)amounts.full_quote=normalize({...candidate,quote:spec.blocks[0]}).amount;
 const passed=Object.values(amounts).every(amount=>amount===spec.expected);if(!passed)failed++;
 console.log(JSON.stringify({...spec,amounts,passed}));
}
console.log(JSON.stringify({tests:cases.length,passed:cases.length-failed,failed,model_requests:0}));process.exitCode=failed?1:0;
